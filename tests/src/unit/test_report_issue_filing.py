# GitHub loaded an 8,167-character /issues/new URL and answered 414 at 8,217
# (measured 2026-09-30).
GITHUB_URL_LIMIT = 8167

SECTIONS = {
    "runtime_bug": (
        "## 🚨 Auto-Generated by `ha_report_issue` Tool",
        "## 📋 Bug Description",
        "## 🔄 Steps to Reproduce",
        "## ✅ Expected vs ❌ Actual Behavior",
        "## 🔧 Environment",
    ),
    "agent_behavior": (
        "## 🤖 Auto-Generated by `ha_report_issue` Tool",
        "## 🤖 What Did the AI Agent Do?",
        "## 🎯 What Should the Agent Have Done?",
        "## 🔧 Tool Calls Made",
        "## 📊 Environment",
    ),
    # The tool calls are the evidence that ha-mcp cannot do it yet.
    "feature_request": (
        "## 💡 Auto-Generated by `ha_report_issue` Tool",
        "## 🔍 What Did the Agent Try?",
        "## 🔧 Tool Calls Made",
        "## 📊 Environment",
    ),
}

# Vendor lists in a template bait the agent into picking one instead of
# stating its own identity.
VENDOR_BAIT = ("Claude, Gemini", "Gemini, GPT", "GPT, Llama")


@pytest.mark.parametrize("report_type", list(SECTIONS))
async def test_report_without_agent_text_has_its_type_sections_and_placeholders(
    core_client: HomeAssistantClient, report_type: str
) -> None:
    """The agent fills these in before showing the report; a type without
    its sections, or a row the agent cannot see is missing, ships a report
    triage cannot use."""
    body = (await report_issue(core_client, report_type=report_type))["issue_body"]

    for heading in SECTIONS[report_type]:
        assert f"\n{heading}" in f"\n{body}"
    for row in ("**AI Model:**", "**MCP Client:**", "**MCP Transport:**"):
        assert row in body
    assert "## 💬 Triggering Prompt & Tool Call" in body
    assert "**User prompt:** <fill in>" in body
    assert "## ⚙️ ha-mcp Configuration" in body
    # Called outside an MCP request, nothing was negotiated.
    assert (
        "**MCP Protocol:** unknown (client capabilities: not sent with this request)"
        in body
    )
    for bait in VENDOR_BAIT:
        assert bait not in body


@pytest.mark.parametrize(
    ("report_type", "prefix"),
    [
        ("runtime_bug", "[BUG] "),
        ("agent_behavior", "[AGENT] "),
        ("feature_request", "[FEATURE] "),
    ],
)
async def test_agent_text_lands_in_the_issue_and_its_link(
    core_client: HomeAssistantClient, report_type: str, prefix: str
) -> None:
    """Without this, the agent rewrites the template by hand and the
    environment or the tool call goes missing. A long tool call is cut so the
    link stays under GitHub's limit, and the issue gate, which closes a report
    without its heading or version line, still finds both in the link."""
    text = {
        "title": "Scripts never appear after create",
        "description": "Created script.test; ha_get_state says not found.",
        "user_prompt": "Make a button that discharges the battery",
        "tool_calls": 'ha_config_set_script(script_id="test") -> created\n'
        + "T" * 9_000,
        "ai_model": "Model X 1.0",
        "client_app": "Claude Desktop 2.2553.1",
        "user_comment": "It said created but I never saw the script.",
    }

    report = await report_issue(core_client, report_type=report_type, **text)

    body = report["issue_body"]
    for key, value in text.items():
        if key != "title":
            assert value in body
    assert "<fill in" not in body
    assert "Claude Desktop 2.2553.1 _(reported by the user)_" in body
    assert report["issue_title"] == prefix + text["title"]
    url = report["issue_url"]
    assert len(url) <= GITHUB_URL_LIMIT
    assert parse_qs(urlsplit(url).query)["title"][0] == report["issue_title"]
    link_body = url_body(url)
    assert text["description"] in link_body
    assert "cut to fit the link" in link_body
    # Text was shortened; the body was not cut from the end.
    assert "Cut to fit the link" not in link_body
    assert link_body.rstrip().endswith(REPORT_END_MARKER)
    for issue in (body, link_body):
        lines = issue.splitlines()
        assert any(
            line.startswith("## ")
            and line.endswith("Auto-Generated by `ha_report_issue` Tool")
            for line in lines
        )
        assert any(line.startswith("- **ha-mcp Version:**") for line in lines)


@pytest.mark.parametrize(
    ("title", "expected"),
    [
        # An agent that already wrote the prefix must not get it twice.
        ("[BUG] already prefixed", "[BUG] already prefixed"),
        # A title that is only the prefix falls back to a generated one.
        ("[BUG]", None),
    ],
)
async def test_title_carries_exactly_one_prefix(
    core_client: HomeAssistantClient, title: str, expected: str | None
) -> None:
    issue_title = (await report_issue(core_client, title=title))["issue_title"]

    if expected is not None:
        assert issue_title == expected
    else:
        assert issue_title.startswith("[BUG] ")
        assert issue_title.removeprefix("[BUG] ").strip()


async def test_long_title_fits_github(core_client: HomeAssistantClient) -> None:
    """GitHub refuses a title over 256 characters."""
    report = await report_issue(core_client, title="x" * 1000)

    assert len(report["issue_title"]) <= 256


async def test_untitled_feature_request_is_not_named_after_a_failed_call(
    core_client: HomeAssistantClient,
) -> None:
    """The fallback title for a bug comes from the last error; a feature
    request named after an unrelated failure misleads triage."""
    await fail_a_tool_call(RuntimeError("entity not found"), "ha_call_service")

    report = await report_issue(core_client, report_type="feature_request")

    assert report["issue_title"].startswith("[FEATURE] ")
    assert "entity not found" not in report["issue_title"]


async def test_link_keeps_redacted_error_messages_and_leaves_the_logs_out(
    write_error_log: Callable[[str], None], core_client: HomeAssistantClient
) -> None:
    """The agent cannot edit the pre-filled link, so a token in a logged
    error would be published as-is when the user clicks Create; a long error
    is cut like the agent's text, and the logs only fit the full body."""
    write_error_log("ERROR something broke\n")
    secret = f"auth failed token=abcd1234secret Bearer {JWT} "
    await fail_a_tool_call(
        RuntimeError(secret + "entity not found " * 500), "ha_call_service"
    )

    report = await report_issue(core_client)

    link_body = url_body(report["issue_url"])
    assert len(report["issue_url"]) <= GITHUB_URL_LIMIT
    assert "## 🚨 Error Messages" in link_body
    assert "auth failed" in link_body
    assert "abcd1234secret" not in link_body
    assert JWT not in link_body
    assert "ERROR something broke" not in link_body
    assert "ERROR something broke" in report["issue_body"]


async def test_report_and_pasted_fences_stay_inside_their_code_blocks(
    core_client: HomeAssistantClient,
) -> None:
    """A chat UI closes a ``` block at the first inner ``` line, so a copied
    report lost everything after it (#2437); agent text with its own ~~~
    fence must not end its block early either."""
    await fail_a_tool_call(RuntimeError("Service not found"), "ha_call_service")
    tool_calls = "first line\n~~~\nlooks like a fence\n~~~~\nlast line"

    body = (await report_issue(core_client, tool_calls=tool_calls))["issue_body"]

    fences = [
        t
        for t in MarkdownIt().parse(f"```markdown\n{body}\n```\n")
        if t.type == "fence"
    ]
    assert len(fences) == 1
    assert fences[0].content == f"{body}\n"
    inner = [t for t in MarkdownIt().parse(body) if t.type == "fence"]
    assert any(t.content == f"{tool_calls}\n" for t in inner)


def _visible(markdown: str) -> str:
    """What a reader sees: no comment text, no code block contents."""
    rendered = MarkdownIt().render(markdown)
    visible = re.sub(r"<!--.*?(?:-->|\Z)", "", rendered, flags=re.S)
    return re.sub(r"<pre>.*?</pre>", "", visible, flags=re.S)


@pytest.mark.parametrize(
    "description",
    [
        "intro\n```\n" + "log line\n" * 1_000 + "```\nrest\n",
        "intro\n<!-- " + "x" * 9_000 + " -->\nrest\n",
        "intro\n~~~\n<!-- sample\n" + "x" * 9_000 + "\n~~~\nrest\n",
    ],
    ids=[
        "inside a code fence",
        "inside an HTML comment",
        "inside a code fence that shows <!--",
    ],
)
async def test_cut_description_keeps_its_note_and_the_environment_visible(
    core_client: HomeAssistantClient, description: str
) -> None:
    """A cut inside an open code fence or HTML comment would hide the note
    that the rest is in the chat, and pull the environment block into it."""
    report = await report_issue(core_client, description=description)

    visible = _visible(url_body(report["issue_url"]))
    assert "cut to fit the link" in visible
    assert "🔧 Environment" in visible


