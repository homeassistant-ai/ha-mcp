"""The finished issue ha_report_issue hands the agent, and how to file it.

The agent files the report without editing it: its own text in the body, a
link GitHub accepts, and a body that survives a chat code block. Each report
comes from ``ha_report_issue`` on the server's own client against a real Core;
failed tool calls are recorded the way every tool records one.
"""

