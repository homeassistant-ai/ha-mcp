async def test_instructions_walk_the_agent_through_filing(
    core_client: HomeAssistantClient,
) -> None:
    """A stale client tool list (#1804) and known Claude Desktop bugs (#2367,
    #2472) were filed as server bugs, and agents guessed the client app or
    wrote the reporter's words themselves. The checks come before the
    duplicate search, and the ``fields`` example an agent copies keeps them."""
    report = await report_issue(core_client)

    instructions = report["instructions"]
    duplicates = instructions.index("Check for duplicates FIRST")
    assert instructions.index("missing_tool_hint") < duplicates
    assert instructions.index("known_client_issues_hint") < duplicates
    assert "refresh" in report["missing_tool_hint"]
    for ticket in ("#2367", "claude-code#92014", "#2472", "claude-code#94608"):
        assert ticket in report["known_client_issues_hint"]
    for asked in ("'runtime_bug'", "'agent_behavior'", "'feature_request'"):
        assert asked in instructions
    for field in (
        "user_prompt",
        "tool_calls",
        "user_comment",
        "ai_model",
        "client_app",
    ):
        assert field in instructions
    assert "user which app and version they are using" in instructions
    assert "NEVER fill it in yourself" in instructions
    for bait in VENDOR_BAIT:
        assert bait not in instructions
    assert "ANONYMIZE" in instructions
    assert "closed after 24 hours" in instructions
    # Four backticks keep the tilde-fenced report in one piece in a chat.
    assert "````markdown" in instructions

    mcp = FastMCP("report-issue")
    register_bug_report_tools(mcp, core_client)
    tool = await mcp.get_tool("ha_report_issue")
    assert tool is not None
    example = re.search(
        r"Typical: '([^']+)'", tool.parameters["properties"]["fields"]["description"]
    )
    assert example is not None
    assert {"missing_tool_hint", "known_client_issues_hint", "instructions"} <= set(
        example.group(1).split(",")
    )


async def test_duplicate_search_uses_the_failed_tool_and_the_error_kind(
    core_client: HomeAssistantClient,
) -> None:
    await fail_a_tool_call(RuntimeError("Connection timeout"), "ha_call_service")

    report = await report_issue(core_client)

    terms = []
    for url in report["duplicate_check_urls"]:
        assert url.startswith("https://github.com/homeassistant-ai/ha-mcp/issues?")
        query = parse_qs(urlsplit(url).query)["q"][0]
        assert query.startswith("is:issue ")
        terms.append(query.removeprefix("is:issue "))
    assert {"ha_call_service", "connection", "timeout"} <= set(terms)


async def test_negotiated_protocol_and_client_capabilities_reach_the_report(
    core_client: HomeAssistantClient,
) -> None:
    """Elicitation and roots support decide which flows a client can run;
    the report shows what this client declared in its handshake."""

    async def elicit(*args: Any) -> None:
        return None

    mcp = FastMCP("report-issue")
    register_bug_report_tools(mcp, core_client)
    async with Client(
        mcp,
        client_info=Implementation(name="probe-client", version="1.0"),
        roots=["file:///workspace"],
        elicitation_handler=elicit,
    ) as client:
        result = await client.call_tool("ha_report_issue", {})
    report = result.structured_content
    assert isinstance(report, dict)

    capabilities = report["diagnostic_info"]["mcp_client_capabilities"]
    assert {"elicitation.form", "roots"} <= set(capabilities)
    assert (
        f"**MCP Protocol:** {LATEST_PROTOCOL_VERSION} (client capabilities: "
        f"{', '.join(capabilities)})"
    ) in report["issue_body"]
